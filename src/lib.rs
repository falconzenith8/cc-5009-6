//! # stage-vol — 舞台灯光体积效果预览器
//!
//! 在程序生成的舞台、幕布与遮挡板场景中预览聚光灯束穿过均匀薄雾的体积效果。
//!
//! ## 结构
//! - [`kernel`]: 体积光内核 —— 数学、场景、参数、有界步数体积积分、控件模式、
//!   计时报告。UI 控件由内核的 control schema 驱动，非法值以错误形式反馈回界面。
//! - [`cpu`]: CPU 参考渲染器，与 GPU 使用同一积分公式，用于测试与参考帧。
//! - [`gpu`]: wgpu 渲染器（阴影深度 pass + 不透明 pass + 体积 raymarch pass +
//!   合成 pass），实时参数经 uniform buffer 上传，支持设备资源恢复。
//!
//! ## 模型边界（不替代真实体积渲染实现）
//! 本预览器实现的是**单散射、各向同性相位、均匀介质**的近似模型：
//! 雾的消光系数 σ 在全场景恒定；只计算一次散射，不含多次散射与介质内
//! 自阴影之外的遮挡；相位函数取各向同性并折入灯光强度；幕布按平面处理
//! （无褶皱位移）；阴影来自聚光灯视角的深度图（CPU 参考路径用解析遮挡）。
//! 因此它适合用于灯光设计预览与参数调试，**不能替代**支持非均匀介质、
//! 多次散射或物理相函数的完整体积渲染器。所有距离单位为米，σ 单位为 1/m，
//! 积分距离有硬上界（[`kernel::params::MAX_RAY_DISTANCE`]），步数有上界
//! （[`kernel::params::MAX_STEPS`]），镜头附近与灯位内部均不会产生无穷值。

pub mod cpu;
pub mod gpu;
pub mod kernel;

/// 模型边界说明（与 crate 文档一致，供 CLI `model-notes` 输出）。
pub fn model_notes() -> &'static str {
    "模型边界说明（stage-vol 预览器，不替代真实体积渲染实现）\n\
     - 单散射近似：只计算一次体积散射，不含多次散射。\n\
     - 各向同性相位：相位函数折入灯光强度，无方向性散射。\n\
     - 均匀介质：雾密度 σ 全场景恒定（均匀薄雾），无非均匀介质。\n\
     - 遮挡：聚光灯视角阴影（GPU 为阴影深度图，CPU 参考为解析遮挡），\n\
       遮挡影响体积内光照，而非在最终画面叠加亮锥。\n\
     - 幕布按平面处理；挡板为长方体。\n\
     - 单位：距离为米，σ 为 1/m；积分距离上界 40 m，步数上界 512，\n\
       采样点距灯最近 0.05 m，镜头附近与灯内观察均有限。"
}
