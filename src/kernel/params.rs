//! Scene parameters, validation, persistence, and the control schema that
//! drives UI widgets. All UI controls are generated from [`control_schema`]
//! and applied through [`StageVolParams::set_control`], so the kernel owns
//! ranges/defaults and rejects invalid values with errors that surface back
//! in the UI ("controls driven by the kernel, failures fed back").

use serde::{Deserialize, Serialize};
use std::path::Path;

pub const MAX_STEPS: u32 = 512;
pub const MAX_LIGHTS: usize = 2;
/// Hard bound on any integration distance, meters. Keeps the integral
/// bounded even when a ray never hits geometry.
pub const MAX_RAY_DISTANCE: f32 = 40.0;

#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub enum ViewMode {
    /// Opaque scene dimmed by transmittance plus in-scattered light.
    Composite,
    /// Only the volumetric contribution L (tone-mapped for display).
    VolumeOnly,
    /// Shadow-map visibility sampled at the first opaque surface.
    Shadow,
    /// Opaque scene only, no volumetric term.
    OpaqueOnly,
}

impl ViewMode {
    pub const ALL: [ViewMode; 4] = [
        ViewMode::Composite,
        ViewMode::VolumeOnly,
        ViewMode::Shadow,
        ViewMode::OpaqueOnly,
    ];
    pub fn label(self) -> &'static str {
        match self {
            ViewMode::Composite => "最终合成",
            ViewMode::VolumeOnly => "体积单独贡献",
            ViewMode::Shadow => "阴影",
            ViewMode::OpaqueOnly => "不透明场景",
        }
    }
    pub fn index(self) -> u32 {
        match self {
            ViewMode::Composite => 0,
            ViewMode::VolumeOnly => 1,
            ViewMode::Shadow => 2,
            ViewMode::OpaqueOnly => 3,
        }
    }
}

#[derive(Clone, Copy, Debug, PartialEq, Serialize, Deserialize)]
pub struct SpotLight {
    pub position: [f32; 3],
    pub target: [f32; 3],
    /// RGB color × intensity (candela-like); the in-scatter source term.
    pub color: [f32; 3],
    pub intensity: f32,
    pub inner_cone_deg: f32,
    pub outer_cone_deg: f32,
    /// Illumination range gate, meters.
    pub range: f32,
    /// Procedural gobo (pattern mask) id; see `gobo` module.
    pub gobo_id: u32,
    /// Gobo pattern tiling scale in light-UV space.
    pub gobo_scale: f32,
    pub enabled: bool,
}

impl Default for SpotLight {
    fn default() -> Self {
        SpotLight {
            position: [0.0, 4.2, 1.5],
            target: [0.0, 0.6, -1.2],
            color: [1.0, 0.85, 0.6],
            intensity: 14.0,
            inner_cone_deg: 12.0,
            outer_cone_deg: 19.0,
            range: 9.0,
            gobo_id: 0,
            gobo_scale: 4.0,
            enabled: true,
        }
    }
}

#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
pub struct StageVolParams {
    /// Fog extinction coefficient σ, 1/m. 0 disables fog exactly.
    pub fog_sigma: f32,
    /// Bounded raymarch step count; the integral converges as steps grow,
    /// it does not simply get brighter (per-segment exponential integrator).
    pub steps: u32,
    pub view_mode: ViewMode,
    pub lights: Vec<SpotLight>,
    /// Occluder panel horizontal offset, meters.
    pub occluder_x: f32,
    /// Occluder panel size multiplier (1 = 1.1 m × 2.3 m).
    pub occluder_scale: f32,
    pub occluder_visible: bool,
    /// Animate the occluder back and forth (used by the moving-occluder test
    /// and the UI preview).
    pub occluder_animate: bool,
    pub camera_pos: [f32; 3],
    pub camera_target: [f32; 3],
    pub camera_fov_deg: f32,
}

impl Default for StageVolParams {
    fn default() -> Self {
        let mut lights = vec![SpotLight::default(); MAX_LIGHTS];
        lights[1].position = [2.6, 4.0, 0.6];
        lights[1].target = [1.2, 0.4, -1.6];
        lights[1].color = [0.45, 0.65, 1.0];
        lights[1].intensity = 9.0;
        lights[1].gobo_id = 1;
        lights[1].enabled = false;
        StageVolParams {
            fog_sigma: 0.09,
            steps: 64,
            view_mode: ViewMode::Composite,
            lights,
            occluder_x: 0.0,
            occluder_scale: 1.0,
            occluder_visible: true,
            occluder_animate: false,
            camera_pos: [0.0, 2.1, 5.6],
            camera_target: [0.0, 1.1, -1.0],
            camera_fov_deg: 42.0,
        }
    }
}

/// Widget description generated by the kernel; the UI renders one control
/// per entry and never hardcodes ranges itself.
#[derive(Clone, Debug)]
pub struct ControlDesc {
    pub id: &'static str,
    pub label: &'static str,
    pub min: f32,
    pub max: f32,
    pub step: f32,
}

