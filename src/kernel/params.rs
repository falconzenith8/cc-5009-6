#[derive(Clone, Debug)]
pub struct ValidationIssue {
    pub field: &'static str,
    pub message: String,
}

impl StageVolParams {
    /// Clamp-free validation: returns every out-of-range or inconsistent
    /// value. Callers (UI/CLI) surface these instead of silently fixing them.
    pub fn validate(&self) -> Vec<ValidationIssue> {
        let mut issues = Vec::new();
        if !(0.0..=0.5).contains(&self.fog_sigma) || !self.fog_sigma.is_finite() {
            issues.push(ValidationIssue { field: "fog_sigma", message: format!("σ={} 超出 [0, 0.5] 1/m", self.fog_sigma) });
        }
        if self.steps == 0 || self.steps > MAX_STEPS {
            issues.push(ValidationIssue { field: "steps", message: format!("步数 {} 超出 [1, {}]", self.steps, MAX_STEPS) });
        }
        for (i, l) in self.lights.iter().enumerate() {
            if l.outer_cone_deg <= l.inner_cone_deg {
                issues.push(ValidationIssue { field: "lights", message: format!("灯{i} 外锥角必须大于内锥角") });
            }
            if !(1.0..=20.0).contains(&l.range) {
                issues.push(ValidationIssue { field: "lights", message: format!("灯{i} 范围 {} 超出 [1, 20] m", l.range) });
            }
            if l.intensity < 0.0 || !l.intensity.is_finite() {
                issues.push(ValidationIssue { field: "lights", message: format!("灯{i} 强度非法") });
            }
        }
        if !(-3.0..=3.0).contains(&self.occluder_x) {
            issues.push(ValidationIssue { field: "occluder_x", message: format!("挡板 x={} 超出 [-3, 3] m", self.occluder_x) });
        }
        if !(0.2..=10.0).contains(&self.occluder_scale) {
            issues.push(ValidationIssue { field: "occluder_scale", message: format!("挡板尺寸倍数 {} 超出 [0.2, 10]", self.occluder_scale) });
        }
        issues
    }

    pub fn get_control(&self, id: &str) -> Option<f32> {
        match id {
            "fog_sigma" => Some(self.fog_sigma),
            "steps" => Some(self.steps as f32),
            "occluder_x" => Some(self.occluder_x),
            "occluder_scale" => Some(self.occluder_scale),
            "light0.intensity" => self.lights.first().map(|l| l.intensity),
            "light0.range" => self.lights.first().map(|l| l.range),
            "light0.outer_cone_deg" => self.lights.first().map(|l| l.outer_cone_deg),
            "light0.gobo_scale" => self.lights.first().map(|l| l.gobo_scale),
            "light1.intensity" => self.lights.get(1).map(|l| l.intensity),
            "light1.range" => self.lights.get(1).map(|l| l.range),
            _ => None,
        }
    }

    /// Apply one control change. Returns Err with a message on unknown id or
    /// rejected value; the caller displays it (failure feedback path).
    pub fn set_control(&mut self, id: &str, value: f32) -> Result<(), String> {
        if !value.is_finite() {
            return Err(format!("控件 {id} 收到非有限值"));
        }
        // Apply to a scratch copy; commit only if the whole parameter set
        // stays valid, so a rejected edit never leaves bad state behind.
        let mut next = self.clone();
        match id {
            "fog_sigma" => next.fog_sigma = value,
            "steps" => next.steps = value.round().max(1.0) as u32,
            "occluder_x" => next.occluder_x = value,
            "occluder_scale" => next.occluder_scale = value,
            "light0.intensity" => next.lights[0].intensity = value,
            "light0.range" => next.lights[0].range = value,
            "light0.outer_cone_deg" => next.lights[0].outer_cone_deg = value,
            "light0.gobo_scale" => next.lights[0].gobo_scale = value,
            "light1.intensity" => next.lights[1].intensity = value,
            "light1.range" => next.lights[1].range = value,
            _ => return Err(format!("未知控件 id: {id}")),
        }
        let issues = next.validate();
        if issues.is_empty() {
            *self = next;
            Ok(())
        } else {
            Err(issues.into_iter().map(|i| i.message).collect::<Vec<_>>().join("; "))
        }
    }

    pub fn save_to(&self, path: &Path) -> std::io::Result<()> {
        let json = serde_json::to_string_pretty(self).expect("params serialize");
        std::fs::write(path, json)
    }

    pub fn load_from(path: &Path) -> Result<Self, String> {
        let text = std::fs::read_to_string(path).map_err(|e| format!("读取 {} 失败: {e}", path.display()))?;
        let params: Self = serde_json::from_str(&text).map_err(|e| format!("解析 {} 失败: {e}", path.display()))?;
        let issues = params.validate();
        if issues.is_empty() {
            Ok(params)
        } else {
            Err(issues.into_iter().map(|i| i.message).collect::<Vec<_>>().join("; "))
        }
    }

    /// Occluder x offset at time `t` when animation is enabled.
    pub fn occluder_x_at(&self, t_seconds: f32) -> f32 {
        if self.occluder_animate {
            self.occluder_x + 1.6 * (t_seconds * 0.9).sin()
        } else {
            self.occluder_x
        }
    }
}
